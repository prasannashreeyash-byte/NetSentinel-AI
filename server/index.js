// Administrator Complaint Investigation & Resolution Update
app.patch('/api/reports/:id', authenticate, requireAdmin, async (req, res) => {
  try {
    const r = await Report.findOne({
      $or: [
        { _id: mongoose.isValidObjectId(req.params.id) ? req.params.id : null },
        { incidentId: req.params.id }
      ]
    });

    if (!r) return res.status(404).json({ error: 'Complaint not found.' });

    // Validate Status
    if (req.body.status !== undefined) {
      const validStatuses = ['Open', 'Under Investigation', 'Under investigation', 'Resolved', 'Closed'];
      if (!validStatuses.includes(req.body.status)) {
        return res.status(400).json({ error: 'Invalid status. Supported: Open, Under Investigation, Resolved, Closed.' });
      }
      r.status = req.body.status === 'Under investigation' ? 'Under Investigation' : req.body.status;
    }

    // Validate Severity
    if (req.body.severity !== undefined) {
      const validSeverities = ['Low', 'Medium', 'High', 'Critical'];
      if (!validSeverities.includes(req.body.severity)) {
        return res.status(400).json({ error: 'Invalid severity. Supported: Low, Medium, High, Critical.' });
      }
      r.severity = req.body.severity;
    }

    // Update String Fields
    const textFields = ['assignee', 'investigationFindings', 'suspectedCause', 'remediation', 'resolutionNotes', 'category'];
    for (const f of textFields) {
      if (req.body[f] !== undefined) {
        r[f] = String(req.body[f]).trim().slice(0, 10000);
      }
    }

    // Update Code Investigation / Correction if provided
    if (req.body.codeCorrection && typeof req.body.codeCorrection === 'object') {
      r.codeCorrection = {
        originalCode: String(req.body.codeCorrection.originalCode || r.codeCorrection?.originalCode || r.codeSnippet || '').slice(0, 25000),
        reportedError: String(req.body.codeCorrection.reportedError || r.codeCorrection?.reportedError || r.errorMessage || '').slice(0, 10000),
        suspectedCause: String(req.body.codeCorrection.suspectedCause || r.codeCorrection?.suspectedCause || '').slice(0, 10000),
        correctedCode: String(req.body.codeCorrection.correctedCode || '').slice(0, 25000),
        explanation: String(req.body.codeCorrection.explanation || '').slice(0, 10000),
        verificationStatus: String(req.body.codeCorrection.verificationStatus || 'Verified & Tested')
      };
    }

    // Append update log note
    if (req.body.note && String(req.body.note).trim()) {
      r.updates.push({
        author: req.user.name,
        role: 'admin',
        message: String(req.body.note).trim().slice(0, 3000),
        createdAt: new Date()
      });
    }

    await r.save();
    await audit(req, 'INVESTIGATE_COMPLAINT', 'Report', r.incidentId, `status=${r.status}; severity=${r.severity}`);
    res.json(r);
  } catch (err) {
    console.error('Update complaint error:', err);
    res.status(400).json({ error: 'Could not update complaint. Check provided fields.' });
  }
});

