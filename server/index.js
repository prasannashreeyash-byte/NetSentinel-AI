// Attachment validation helper (secure size & MIME-type validation)
function validateAttachment(attachment) {
  if (!attachment || typeof attachment !== 'object') return null;
  const name = String(attachment.name || '').trim();
  const mimeType = String(attachment.mimeType || attachment.type || '').trim().toLowerCase();
  const size = Number(attachment.size || 0);
  const dataUrl = String(attachment.dataUrl || attachment.data || '').trim();

  if (!name && !dataUrl) return null;

  // Maximum file size: 5 MB
  const MAX_SIZE = 5 * 1024 * 1024;
  if (size > MAX_SIZE || (dataUrl && dataUrl.length > MAX_SIZE * 1.4)) {
    throw new Error('Attachment exceeds maximum allowed size of 5 MB.');
  }

  // Reject executable and dangerous extensions
  const dangerousExts = /\.(exe|bat|cmd|com|msi|vbs|vbe|js|jse|ws|wsf|scr|dll|sys|jar|bin|sh|bash|ps1)$/i;
  if (dangerousExts.test(name)) {
    throw new Error('For security reasons, executable files (.exe, .bat, scripts) cannot be uploaded as attachments.');
  }

  // Allowed MIME categories: images, plain text, documents, code, logs, json, pdf
  const allowedTypes = [
    'image/png', 'image/jpeg', 'image/jpg', 'image/gif', 'image/webp', 'image/svg+xml',
    'text/plain', 'text/markdown', 'text/csv', 'text/log', 'application/json',
    'text/javascript', 'application/javascript', 'text/x-python', 'application/pdf',
    'text/html', 'text/css'
  ];

  if (mimeType && !allowedTypes.includes(mimeType) && !mimeType.startsWith('image/') && !mimeType.startsWith('text/')) {
    throw new Error('Unsupported attachment type. Allowed types: Images (PNG, JPG, WebP), Text files, Logs, Code, JSON, PDF.');
  }

  return {
    name: name.slice(0, 150) || 'attachment',
    mimeType: mimeType || 'application/octet-stream',
    size: size || Math.round(dataUrl.length * 0.75),
    dataUrl: dataUrl.slice(0, 7 * 1024 * 1024)
  };
}

