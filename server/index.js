// Secure Password Reset Initiation
app.post('/api/auth/forgot-password', async (req, res) => {
  try {
    const email = String(req.body.email || '').trim().toLowerCase();
    if (!email) return res.status(400).json({ error: 'Please provide your account email address.' });

    const user = await User.findOne({ email });
    if (!user) {
      return res.status(404).json({ error: 'No account was found with that email address.' });
    }

    // Generate secure 32-byte cryptographic token
    const rawResetToken = crypto.randomBytes(32).toString('hex');
    const hashedToken = crypto.createHash('sha256').update(rawResetToken).digest('hex');

    user.resetPasswordToken = hashedToken;
    user.resetPasswordExpires = Date.now() + 15 * 60 * 1000; // 15-minute validity window
    await user.save();

    await audit({ user }, 'PASSWORD_RESET_REQUESTED', 'User', user._id);

    // In local hackathon demo environment, return the token so the user can complete the reset directly
    res.json({
      success: true,
      message: 'Password reset initiated. Use the generated reset token within 15 minutes to configure a new password.',
      resetToken: rawResetToken
    });
  } catch (err) {
    console.error('Forgot password error:', err);
    res.status(500).json({ error: 'Could not process password reset request.' });
  }
});

// Secure Password Reset Execution
app.post('/api/auth/reset-password', async (req, res) => {
  try {
    const token = String(req.body.token || '').trim();
    const newPassword = String(req.body.newPassword || '');

    if (!token) return res.status(400).json({ error: 'Password reset token is required.' });
    if (newPassword.length < 8 || !/[A-Za-z]/.test(newPassword) || !/[0-9]/.test(newPassword)) {
      return res.status(400).json({ error: 'New password must be at least 8 characters and include both letters and numbers.' });
    }

    const hashedToken = crypto.createHash('sha256').update(token).digest('hex');
    const user = await User.findOne({
      resetPasswordToken: hashedToken,
      resetPasswordExpires: { $gt: Date.now() }
    }).select('+resetPasswordToken +resetPasswordExpires');

    if (!user) {
      return res.status(400).json({ error: 'Password reset token is invalid or has expired. Please request a new reset.' });
    }

    user.passwordHash = await bcrypt.hash(newPassword, 12);
    user.resetPasswordToken = undefined;
    user.resetPasswordExpires = undefined;
    await user.save();

    await audit({ user }, 'PASSWORD_RESET_COMPLETED', 'User', user._id);
    res.json({ success: true, message: 'Password has been successfully updated. You may now log in.' });
  } catch (err) {
    console.error('Reset password error:', err);
    res.status(500).json({ error: 'Failed to reset password.' });
  }
});

// Google OAuth verification
app.post('/api/auth/google', async (req, res) => {
  try {
    if (!process.env.GOOGLE_CLIENT_ID) {
      return res.status(503).json({ error: 'Google sign-in is not configured on this server.' });
    }
    const ticket = await googleClient.verifyIdToken({
      idToken: req.body.credential,
      audience: process.env.GOOGLE_CLIENT_ID
    });
    const p = ticket.getPayload();
    if (!p?.email || !p.email_verified) {
      return res.status(401).json({ error: 'Google account email could not be verified.' });
    }
    let user = await User.findOne({ $or: [{ googleSub: p.sub }, { email: p.email.toLowerCase() }] });
    if (user) {
      if (!user.active) return res.status(403).json({ error: 'Account disabled.' });
      if (user.googleSub && user.googleSub !== p.sub) return res.status(409).json({ error: 'Google account is linked differently.' });
      user.googleSub = p.sub;
      await user.save();
    } else {
      user = await User.create({
        name: p.name || p.email.split('@')[0],
        email: p.email.toLowerCase(),
        googleSub: p.sub,
        role: 'user'
      });
    }
    res.json({ token: issueToken(user), user: publicUser(user) });
  } catch {
    return res.status(401).json({ error: 'Google sign-in verification failed.' });
  }
});

