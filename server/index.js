// User Registration - Public registration always assigns 'user' role
app.post('/api/auth/register', async (req, res) => {
  try {
    const name = String(req.body.name || '').trim();
    const email = String(req.body.email || '').trim().toLowerCase();
    const password = String(req.body.password || '');

    if (name.length < 2 || name.length > 100) {
      return res.status(400).json({ error: 'Name must contain between 2 and 100 characters.' });
    }
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      return res.status(400).json({ error: 'Please enter a valid email address.' });
    }
    if (password.length < 8 || !/[A-Za-z]/.test(password) || !/[0-9]/.test(password)) {
      return res.status(400).json({ error: 'Password must be at least 8 characters long and include both letters and numbers.' });
    }

    if (await User.findOne({ email })) {
      return res.status(409).json({ error: 'An account with this email address already exists. Please sign in.' });
    }

    const user = await User.create({
      name,
      email,
      passwordHash: await bcrypt.hash(password, 12),
      role: 'user', // strictly enforced: public registration cannot create administrators
      active: true
    });

    await audit(req, 'USER_REGISTER', 'User', user._id, `email=${email}; role=user`);
    res.status(201).json({ token: issueToken(user), user: publicUser(user) });
  } catch (e) {
    console.error('Registration error:', e);
    res.status(500).json({ error: e.code === 11000 ? 'An account with this email already exists.' : 'Registration failed. Check server logs.' });
  }
});

// Standard User Login (can be accessed from /user/login)
app.post('/api/auth/login', async (req, res) => {
  try {
    const email = String(req.body.email || '').trim().toLowerCase();
    const password = String(req.body.password || '');

    if (!email || !password) {
      return res.status(400).json({ error: 'Please enter both email and password.' });
    }

    const user = await User.findOne({ email }).select('+passwordHash');
    if (!user || !user.passwordHash || !(await bcrypt.compare(password, user.passwordHash))) {
      return res.status(401).json({ error: 'Incorrect email or password.' });
    }
    if (!user.active) {
      return res.status(403).json({ error: 'This account has been deactivated. Please contact an administrator.' });
    }

    // If request specifies requiredRole (e.g. from admin portal)
    if (req.body.requiredRole === 'admin' && user.role !== 'admin') {
      return res.status(403).json({ error: 'Access denied. Administrator privileges are required to access this portal.' });
    }

    await audit({ user }, 'USER_LOGIN', 'User', user._id, `role=${user.role}`);
    res.json({ token: issueToken(user), user: publicUser(user) });
  } catch (err) {
    console.error('Login error:', err);
    res.status(500).json({ error: 'Login failed due to a server error. Please try again.' });
  }
});

